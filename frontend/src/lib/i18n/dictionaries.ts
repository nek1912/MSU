type Vars = Record<string, string | number>;

function interp(s: string, vars?: Vars): string {
  if (!vars) return s;
  return Object.entries(vars).reduce(
    (acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)),
    s,
  );
}

