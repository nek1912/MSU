"""Re-embed all chunks using the current Jina provider.

This fixes the embedding provenance mismatch where stored embeddings
were generated by Gemini but queries use Jina.
"""
import os
import json
import time
from pathlib import Path
from dotenv import load_dotenv

load_dotenv('backend/.env', override=True)
from supabase import create_client
from app.providers.embeddings import get_embedding_provider

PROJECT_ROOT = Path(__file__).parent.parent
url = os.environ['SUPABASE_URL']
key = os.environ['SUPABASE_SERVICE_KEY']
supabase = create_client(url, key)
provider = get_embedding_provider()


def reembed_all_chunks():
    """Re-embed all chunks using the current provider."""
    print("=== RE-EMBEDDING ALL CHUNKS ===")
    print(f"Provider: {provider.__class__.__name__}")
    print(f"Model: {provider._model}")
    print()
    
    # Get all chunks
    chunks = supabase.table('chunks').select('id, content').execute().data
    print(f"Total chunks to re-embed: {len(chunks)}")
    
    # Process in batches
    batch_size = 50
    total_batches = (len(chunks) + batch_size - 1) // batch_size
    
    start_time = time.time()
    updated = 0
    errors = []
    
    for batch_idx in range(total_batches):
        start = batch_idx * batch_size
        end = min(start + batch_size, len(chunks))
        batch = chunks[start:end]
        
        print(f"Batch {batch_idx + 1}/{total_batches} ({len(batch)} chunks)...")
        
        # Extract texts
        texts = [c['content'] for c in batch]
        chunk_ids = [c['id'] for c in batch]
        
        try:
            # Generate embeddings
            embeddings = provider.embed_texts(texts)
            
            # Update each chunk
            for chunk_id, embedding in zip(chunk_ids, embeddings):
                supabase.table('chunks').update({
                    'embedding': json.dumps(embedding)
                }).eq('id', chunk_id).execute()
                updated += 1
            
            print(f"  Updated {len(batch)} chunks")
            
        except Exception as e:
            print(f"  ERROR: {e}")
            errors.extend([(chunk_ids[i], str(e)) for i in range(len(batch))])
        
        # Small delay between batches
        if batch_idx < total_batches - 1:
            time.sleep(0.5)
    
    elapsed = time.time() - start_time
    
    print(f"\n=== RE-EMBEDDING COMPLETE ===")
    print(f"Updated: {updated}/{len(chunks)}")
    print(f"Errors: {len(errors)}")
    print(f"Duration: {elapsed:.1f}s")
    
    if errors:
        print("\nErrors:")
        for chunk_id, error in errors[:5]:
            print(f"  {chunk_id}: {error}")
    
    return updated, errors


def verify_reembedding():
    """Verify that re-embedding worked correctly."""
    print("\n=== VERIFICATION ===")
    
    # Test query
    query = "What are the byelaws for a cooperative society?"
    query_embedding = provider.embed_texts([query])[0]
    
    # Get a chunk
    chunk = supabase.table('chunks').select('id, content, embedding').limit(1).execute().data[0]
    stored_embedding = json.loads(chunk['embedding'])
    
    # Compute similarity
    cosine = sum(a * b for a, b in zip(query_embedding, stored_embedding))
    
    print(f"Query: {query[:50]}...")
    print(f"Chunk: {chunk['content'][:50]}...")
    print(f"Similarity: {cosine:.4f}")
    print(f"Expected: > 0.5 (was 0.03 before re-embedding)")
    
    # Test with gold chunk
    gold_chunk_id = '8f055eab-cbe2-4870-b530-9dce2aed131e'
    gold_result = supabase.table('chunks').select('content, embedding').eq('id', gold_chunk_id).execute()
    if gold_result.data:
        gold_embedding = json.loads(gold_result.data[0]['embedding'])
        gold_cosine = sum(a * b for a, b in zip(query_embedding, gold_embedding))
        print(f"\nGold chunk similarity: {gold_cosine:.4f}")
        print(f"Expected: > 0.5 (was 0.038 before re-embedding)")
    
    return cosine > 0.5


if __name__ == '__main__':
    # Re-embed
    updated, errors = reembed_all_chunks()
    
    # Verify
    if updated > 0 and not errors:
        verify_reembedding()
    else:
        print("\nRe-embedding had errors - skipping verification")
